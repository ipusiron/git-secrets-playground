const i18n = (() => {
  let language = 'ja';
  const listeners = [];
  const rendered = new Map();

  function t(key, values = {}) {
    const message = dictionaries[language][key];
    if (message === undefined) throw new Error('Missing translation: ' + key);
    const output = message.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
    rendered.set(output, { key, values });
    return output;
  }

  function translateRendered(text) {
    const entry = rendered.get(text);
    return entry ? t(entry.key, entry.values) : text;
  }

  function apply() {
    document.documentElement.lang = language;
    document.title = t('document.title');
    document.querySelectorAll('[data-i18n]').forEach(node => {
      node.textContent = t(node.dataset.i18n);
    });
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      document.querySelectorAll('[data-i18n-' + attr + ']').forEach(node => {
        node.setAttribute(attr, t(node.getAttribute('data-i18n-' + attr)));
      });
    }
  }

  function setLanguage(next) {
    if (!Object.hasOwn(dictionaries, next)) return;
    language = next;
    try { localStorage.setItem('gitsecrets-language', language); } catch { /* Optional storage. */ }
    apply();
    listeners.forEach(listener => listener());
  }

  function init() {
    const query = new URLSearchParams(location.search).get('lang');
    let saved;
    try { saved = localStorage.getItem('gitsecrets-language'); } catch { /* Optional storage. */ }
    language = Object.hasOwn(dictionaries, query) ? query : Object.hasOwn(dictionaries, saved) ? saved :
      navigator.language.startsWith('ja') ? 'ja' : 'en';
    apply();
  }

  return { t, apply, init, setLanguage, translateRendered, onChange: fn => listeners.push(fn), get language() { return language; } };
})();

if (typeof module !== 'undefined' && module.exports) module.exports = { dictionaries, i18n };
if (typeof document !== 'undefined') i18n.init();
